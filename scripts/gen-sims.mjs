// Builds src/content/sims.ts from the Python sources in scripts/sims/.
// The sims are stand-ins for tkinter and pygame that run in the in-app Python (Pyodide),
// so code questions can use the real library API without a window. Run: npm run gen-sims
import fs from 'node:fs';
import path from 'node:path';
const dir = path.join(import.meta.dirname, 'sims');
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
const lit = (name, src) => {
  if (src.includes('`') || src.includes('${')) throw new Error(name + ' contains a backtick or ${');
  return `export const ${name} = String.raw\`${src}\`;\n`;
};
let out = '// GENERATED by scripts/gen-sims.mjs from scripts/sims/*.py — do not edit by hand.\n/* eslint-disable */\n';
out += lit('TK_SIM', read('tk_opts.py') + read('tksim.py'));
if (fs.existsSync(path.join(dir, 'pgsim.py'))) out += lit('PG_SIM', read('pg_consts.py') + read('pgsim.py'));
fs.writeFileSync(path.join(import.meta.dirname, '..', 'src', 'content', 'sims.ts'), out);
console.log('wrote src/content/sims.ts');
