"""Writes pg_consts.py (constants, key names, colour names) from the REAL pygame, so the stand-in agrees exactly.
usage: python gen_pg_consts.py   (needs pygame installed)"""
import os
os.environ["SDL_VIDEODRIVER"] = "dummy"; os.environ["SDL_AUDIODRIVER"] = "dummy"
import pygame, pygame.constants as C, pygame.color as PC
pygame.init()
EVENTS = "QUIT ACTIVEEVENT KEYDOWN KEYUP MOUSEMOTION MOUSEBUTTONUP MOUSEBUTTONDOWN MOUSEWHEEL JOYAXISMOTION JOYBALLMOTION JOYHATMOTION JOYBUTTONUP JOYBUTTONDOWN VIDEORESIZE VIDEOEXPOSE SYSWMEVENT USEREVENT NUMEVENTS TEXTINPUT TEXTEDITING WINDOWCLOSE WINDOWFOCUSGAINED WINDOWFOCUSLOST WINDOWENTER WINDOWLEAVE WINDOWRESIZED WINDOWMINIMIZED WINDOWRESTORED AUDIODEVICEADDED DROPFILE FINGERDOWN".split()
FLAGS = "SRCALPHA FULLSCREEN RESIZABLE NOFRAME DOUBLEBUF SCALED HWSURFACE OPENGL SWSURFACE BLEND_ADD BLEND_SUB BLEND_MULT BLEND_MIN BLEND_MAX BLEND_RGBA_ADD BLEND_RGB_ADD".split()
consts = {}
for k in dir(C):
    v = getattr(C, k)
    if isinstance(v, int) and (k.startswith(("K_", "KMOD_", "BUTTON_")) or k in EVENTS or k in FLAGS):
        consts[k] = v
keynames = {}
for k, v in consts.items():
    if k.startswith("K_"):
        keynames.setdefault(v, pygame.key.name(v))
cols = {k: tuple(v) for k, v in PC.THECOLORS.items() if not k[-1].isdigit() and " " not in k}
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "pg_consts.py"), "w") as f:
    f.write("# GENERATED by gen_pg_consts.py from real pygame %s - do not edit by hand.\n" % pygame.version.ver)
    f.write("_PG_CONSTS = " + repr(consts) + "\n")
    f.write("_PG_KEYNAMES = " + repr(keynames) + "\n")
    f.write("_PG_COLORS = " + repr(cols) + "\n")
txt = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "pg_consts.py")).read()
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "pg_consts.py"), "w").write(txt.replace("`", "\\x60"))  # the sims are embedded in a JS template string
print(len(consts), len(keynames), len(cols))
